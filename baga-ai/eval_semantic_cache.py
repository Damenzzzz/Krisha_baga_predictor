"""Подбор порога смыслового кэша (semantic_cache.py).

Жёсткая подпись уже не даёт спутать «до 400» и «до 500». Остаётся опасный случай, который
решает только порог косинуса: цифры те же, а СТИЛЬ другой — «светлая кухня» против
«тёмная кухня». Стиль уходит в поиск по фото, и ошибка кэша тут = чужая выдача.

  SAME — перефразировки (тот же смысл, та же подпись): должны попадать в кэш;
  DIFF — та же подпись, другой смысл: попадать НЕ должны.

Метрика выбора: ноль ложных попаданий на DIFF (ошибка кэша дороже промаха), при этом
максимум попаданий на SAME. Запуск: python eval_semantic_cache.py
"""
import numpy as np

from semantic_cache import _embed_alem, _norm, signature

SAME = [
    ("двушка в Алматы до 400 тысяч, светлая кухня", "2-комнатная алматы до 400 тыс, кухня светлая"),
    ("однушка в Бостандыке до 250к", "однокомнатная квартира в Бостандыкском районе до 250 тысяч"),
    ("квартира с панорамными окнами", "квартира с панорамным остеклением"),
    ("лофт с кирпичной стеной", "интерьер в стиле лофт, стена из кирпича"),
    ("трешка не первый этаж до 600 000", "трехкомнатная, не первый этаж, до 600 тыс"),
    ("светлая квартира со свежим ремонтом", "светлая квартира, свежий ремонт"),
    ("квартира без мебели", "квартира не меблированная, без мебели"),
    ("вид на горы из окна", "из окна видно горы"),
    ("кухня-гостиная с островом", "кухня гостиная с кухонным островом"),
    ("скандинавский стиль, белые стены", "белые стены, скандинавский интерьер"),
    ("двушка до 300к в Медеуском районе", "2к в медеуском р-не до 300 тысяч"),
    ("санузел с душевой кабиной", "ванная комната с душевой кабиной"),
    ("современный ремонт, двушка", "двухкомнатная с современным ремонтом"),
    ("квартира с большим балконом", "квартира, большой балкон"),
    ("минимализм в спальне", "спальня в стиле минимализм"),
]
DIFF = [
    ("двушка в Алматы до 400 тысяч, светлая кухня", "двушка в Алматы до 400 тысяч, тёмная кухня"),
    ("квартира с мебелью", "квартира без мебели"),
    ("лофт с кирпичной стеной", "классика с лепниной"),
    ("светлая квартира со свежим ремонтом", "квартира требует ремонта"),
    ("скандинавский стиль, белые стены", "яркие зелёные стены"),
    ("современный ремонт, двушка", "советский ремонт, двушка"),
    ("вид на горы из окна", "вид на город из окна"),
    ("кухня с деревянной столешницей", "кухня с каменной столешницей"),
    ("квартира с большим балконом", "квартира без балкона"),
    ("минимализм в спальне", "спальня с ковром и стенкой"),
    ("панорамные окна", "маленькие окна"),
    ("новый жилой комплекс", "старый фонд, хрущёвка"),
    ("тихий двор", "окна на шумную улицу"),
    ("светлая ванная с белой плиткой", "ванная с тёмной плиткой"),
    ("уютная квартира в тёплых тонах", "квартира в холодных серых тонах"),
]


def cos(a, b):
    va, vb = _embed_alem(_norm(a)), _embed_alem(_norm(b))
    return float(va @ vb / (np.linalg.norm(va) * np.linalg.norm(vb)))


def run():
    same = [(a, b, signature(a) == signature(b), cos(a, b)) for a, b in SAME]
    diff = [(a, b, signature(a) == signature(b), cos(a, b)) for a, b in DIFF]
    print("SAME (должны попадать):  подпись совпала", sum(s for _, _, s, _ in same), "из", len(same))
    print("DIFF (не должны):        подпись совпала", sum(s for _, _, s, _ in diff), "из", len(diff))
    print("\nпорог  попаданий SAME  ложных DIFF")
    best = None
    for t in np.arange(0.80, 0.991, 0.01):
        hit = sum(s and c >= t for _, _, s, c in same)
        false = sum(s and c >= t for _, _, s, c in diff)
        print(f"{t:.2f}   {hit:2d}/{len(same)}          {false:2d}/{len(diff)}")
        if false == 0 and best is None:
            best = (round(float(t), 2), hit)
    print("\nсамые похожие пары из DIFF:")
    for a, b, s, c in sorted(diff, key=lambda x: -x[3])[:5]:
        print(f"  {c:.3f} {'[подпись =]' if s else '[подпись ≠]'} «{a}» / «{b}»")
    print("\nсамые непохожие пары из SAME:")
    for a, b, s, c in sorted(same, key=lambda x: x[3])[:5]:
        print(f"  {c:.3f} {'[подпись =]' if s else '[подпись ≠]'} «{a}» / «{b}»")
    print(f"\nминимальный порог без ложных попаданий: {best[0]} — попаданий на перефразировках {best[1]}/{len(same)}")
    return best


if __name__ == "__main__":
    run()
